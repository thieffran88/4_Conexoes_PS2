/* Glifos extras: setas e pontuação espanhola invertida. */
static const unsigned char EXTRA[][GLYPH_H] = {
    {0x00,0x04,0x08,0x1F,0x08,0x04,0x00}, /* ← */
    {0x00,0x04,0x02,0x1F,0x02,0x04,0x00}, /* → */
    {0x04,0x0E,0x15,0x04,0x04,0x04,0x00}, /* ↑ */
    {0x00,0x04,0x04,0x04,0x15,0x0E,0x04}, /* ↓ */
    {0x04,0x00,0x04,0x04,0x04,0x04,0x04}, /* ¡ */
    {0x04,0x00,0x04,0x08,0x10,0x11,0x0E}, /* ¿ */
};
#define EXTRA_BASE 128

enum { ACC_NONE, ACC_ACUTE, ACC_GRAVE, ACC_CIRC, ACC_TILDE, ACC_CEDIL };

/* Marcas de 2 linhas: acentos acima da letra, cedilha abaixo. */
static const unsigned char MARKS[][2] = {
    {0x00, 0x00},
    {0x02, 0x04}, /* agudo */
    {0x08, 0x04}, /* grave */
    {0x04, 0x0A}, /* circunflexo */
    {0x0D, 0x16}, /* til */
    {0x04, 0x08}, /* cedilha */
};

/* Lê um código UTF-8 e avança o ponteiro. */
static unsigned int next_cp(const char **p)
{
    const unsigned char *s = (const unsigned char *)*p;
    unsigned int cp;
    if (s[0] < 0x80) {
        cp = s[0];
        *p += 1;
    } else if ((s[0] & 0xE0) == 0xC0 && s[1]) {
        cp = ((s[0] & 0x1F) << 6) | (s[1] & 0x3F);
        *p += 2;
    } else if ((s[0] & 0xF0) == 0xE0 && s[1] && s[2]) {
        cp = ((s[0] & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
        *p += 3;
    } else {
        cp = '?';
        *p += 1;
    }
    return cp;
}

/* Converte o código em letra base maiúscula + marca. */
static int decompose(unsigned int cp, int *mark)
{
    *mark = ACC_NONE;
    if (cp >= 'a' && cp <= 'z')
        return (int)(cp - 32);
    if (cp >= 0xE0 && cp <= 0xFE && cp != 0xF7)
        cp -= 0x20; /* minúsculas latinas -> maiúsculas */
    switch (cp) {
    case 0xC1: *mark = ACC_ACUTE; return 'A';
    case 0xC0: *mark = ACC_GRAVE; return 'A';
    case 0xC2: *mark = ACC_CIRC;  return 'A';
    case 0xC3: *mark = ACC_TILDE; return 'A';
    case 0xC9: *mark = ACC_ACUTE; return 'E';
    case 0xCA: *mark = ACC_CIRC;  return 'E';
    case 0xCD: *mark = ACC_ACUTE; return 'I';
    case 0xD3: *mark = ACC_ACUTE; return 'O';
    case 0xD4: *mark = ACC_CIRC;  return 'O';
    case 0xD5: *mark = ACC_TILDE; return 'O';
    case 0xDA: *mark = ACC_ACUTE; return 'U';
    case 0xC7: *mark = ACC_CEDIL; return 'C';
    case 0xD1: *mark = ACC_TILDE; return 'N';
    case 0x2190: case 0x01: return EXTRA_BASE + 0;
    case 0x2192: case 0x02: return EXTRA_BASE + 1;
    case 0x2191: return EXTRA_BASE + 2;
    case 0x2193: return EXTRA_BASE + 3;
    case 0xA1: return EXTRA_BASE + 4;
    case 0xBF: return EXTRA_BASE + 5;
    default: break;
    }
    if (cp >= 32 && cp <= 'Z')
        return (int)cp;
    return '?';
}

float font_width(const char *text, float scale)
{
    int n = 0;
    while (*text) {
        next_cp(&text);
        n++;
    }
    if (n == 0)
        return 0.0f;
    return (float)(n * ADVANCE - 1) * scale;
}

static void draw_bits(unsigned char bits, float x, float y, float s,
                      FontRectFn rect, void *user)
{
    int col = 0;
    while (col < GLYPH_W) {
        /* agrupa pixels consecutivos num único retângulo */
        if (bits & (0x10 >> col)) {
            int start = col;
            while (col < GLYPH_W && (bits & (0x10 >> col)))
                col++;
            rect(x + start * s, y, (col - start) * s, s, user);
        } else {
            col++;
        }
    }
}

void font_draw(const char *text, float x, float y, float scale,
               FontRectFn rect, void *user)
{
    while (*text) {
        int mark, row;
        int ch = decompose(next_cp(&text), &mark);
        const unsigned char *g = ch >= EXTRA_BASE ? EXTRA[ch - EXTRA_BASE]
                                                  : GLYPHS[ch - 32];

        for (row = 0; row < GLYPH_H; row++)
            draw_bits(g[row], x, y + row * scale, scale, rect, user);

        if (mark == ACC_CEDIL) {
            draw_bits(MARKS[mark][0], x, y + GLYPH_H * scale, scale, rect, user);
            draw_bits(MARKS[mark][1], x, y + (GLYPH_H + 1) * scale, scale, rect, user);
        } else if (mark != ACC_NONE) {
            draw_bits(MARKS[mark][0], x, y - 3 * scale, scale, rect, user);
            draw_bits(MARKS[mark][1], x, y - 2 * scale, scale, rect, user);
        }
        x += ADVANCE * scale;
    }
}
